export interface BlogTopic {
  key: string;
  label: string;
  blurb: string;
}

// A domain owns its topic keys. Nothing enforces that two domains do not share
// a key beyond check-blog-posts.js, which fails the build if a post's topic is
// not among its own domain's.
export interface BlogDomainMeta {
  key: BlogDomain;
  label: string;
  topics: BlogTopic[];
}

// A post as authored in blog-posts.ts, before the PDF's own metadata is merged in.
export interface BlogEntry {
  name: string;
  desc: string;
  domain: BlogDomain;
  topic: string;         // primary topic key — must belong to `domain`
  alsoTopics?: string[];  // secondary topics the post also answers to
  level: BlogLevel;
  // Optional only for planned entries. A published post must have one, and the
  // build check fails if it points at a PDF that is not on disk.
  link?: string;
  // Controls visibility only: hidden from visitors behind the unlock at the
  // bottom of the page. Orthogonal to whether a PDF exists — a planned entry
  // with a `link` is readable once unlocked, one without is not yet written.
  planned?: true;
  // When the post went up. This, and not the PDF's compile date, fixes its
  // position in the stream. Compile dates cannot do that job: rebuilding for an
  // unrelated preamble change rewrites them, so on 2026-08-23 a sweep across the
  // LaTeX tree stamped nearly every post with the same day and flattened two
  // years of chronology. Hand-authored because nothing on disk remembers it —
  // these were recovered from the earliest /CreationDate for each PDF in git.
  published?: string;     // ISO; required for anything not `planned`
  // Optional override for the "updated" marker, which otherwise shows the PDF's
  // last compile date. Set it when a rebuild was not a revision, or clear it to
  // suppress the marker on a post whose compile date says more about the build
  // system than about the writing.
  updated?: string;       // ISO
  // Needed only by a planned entry with no PDF, since nothing else can supply a
  // date. Without it the entry sorts to the bottom instead of into the stream.
  intendedDate?: string;  // ISO
}

// A post as rendered: the authored entry plus what gen-blog-manifest.js read out
// of the PDF. The metadata fields are optional because a post whose PDF has not
// been compiled yet should degrade to an entry without a date, not vanish.
export interface BlogPost extends BlogEntry {
  file: string;           // PDF basename — the manifest key; '' when planned
  domainLabel: string;
  topicLabel: string;
  alsoLabels: string[];   // display labels for alsoTopics, resolved once here
  levelLabel: string;
  levelShort: string;
  // The position key and the date on the card: `published`, or `intendedDate`
  // for a planned entry that has no PDF yet.
  published?: string;
  // Shown as "updated ..." beside the date, and only when it is later than
  // `published` — otherwise every post carries a redundant second date equal to
  // its first.
  updatedNote?: string;
  pages?: number;
  readingMinutes?: number;
}

// One entry per PDF in the manifest generated by scripts/gen-blog-manifest.js.
export interface BlogPdfMeta {
  pages: number | null;
  updated: string | null;
  readingMinutes: number | null;
}
export type BlogManifest = Record<string, BlogPdfMeta>;
